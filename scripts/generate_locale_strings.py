def write_xml(folder: str, lang: str) -> None:
    tr = TRANSLATIONS[lang]
    lines = [
        '<?xml version="1.0" encoding="utf-8"?>',
        "<resources>",
    ]
    for key in KEYS_ORDER:
        val = tr[key]
        esc = xu.escape(val)
        lines.append(f'    <string name="{key}">{esc}</string>')
    lines.append("</resources>")
    path = os.path.join(BASE, folder, "strings.xml")
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w", encoding="utf-8") as f:
        f.write("\n".join(lines) + "\n")


def main() -> None:
    for lang, folder in FOLDER_MAP.items():
        write_xml(folder, lang)
    print("Wrote", len(FOLDER_MAP), "locale files")


if __name__ == "__main__":
    main()
